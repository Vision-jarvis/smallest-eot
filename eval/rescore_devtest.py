"""Rescore every saved prediction file on the 200-turn dev-test half (never the sealed half).

    python -m eval.rescore_devtest

Reads results/eot_bench_hi/clean/*/predictions.parquet (our runs on all 400 turns) and LiveKit's
committed predictions, keeps only dev-test ids (eval/split.py), and writes
results/eot_bench_hi_devtest/rescored.md and rescored.json. It also runs the paired bootstrap
over turns that answers "is v0.1 better than Smart Turn v3.2?" on the same 200 turns.
Nothing here reads or prints a sealed-half number.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from eval import metrics
from eval.report import PUB, PUBLISHED, ms, name_of, pct
from eval.split import ids_of

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "results/eot_bench_hi/clean"
OUT = ROOT / "results/eot_bench_hi_devtest"
MAIN = ["pulse_eot_hi", "pulse_eot_hi__full", "smart_turn_v32_fp32", "smart_turn_v32", "hinglish_turn", "silero_timer"]


def _row(name: str, pred: pd.DataFrame, sp: float | None) -> dict:
    _, s = metrics.summarise(pred, sp)
    return {"system": name, **{k: s[k] for k in ("FCR@300", "FCR@600", "Lat@5%", "Lat@10%", "n_hold", "n_eot")}, "knobs_lat5": s["operating_points"]["lat_at_5pct"]}


def paired_bootstrap(a: pd.DataFrame, b: pd.DataFrame, ka: dict, kb: dict, sp_a, sp_b, n: int = 1000, seed: int = 0) -> dict:
    """Resample turns; each system at its own fixed knobs. Returns mean diff (a - b) and 95% CI."""
    oa, ob = metrics.apply_knobs(a, ka, sp_a), metrics.apply_knobs(b, kb, sp_b)
    ids = np.array(sorted(set(oa.id) & set(ob.id)))

    def per_turn(o: pd.DataFrame) -> pd.DataFrame:
        h = o[o.label == "hold"].groupby("id")["cut"].agg(["sum", "size"])
        e = o[o.label == "eot"].groupby("id")["latency"].agg(["sum", "size"])
        return pd.concat([h.add_prefix("h_"), e.add_prefix("e_")], axis=1).reindex(ids).fillna(0.0)

    pa, pb = per_turn(oa), per_turn(ob)
    rng = np.random.default_rng(seed)
    d_lat, d_fcr = [], []
    for _ in range(n):
        s = rng.integers(0, len(ids), len(ids))
        A, B = pa.iloc[s].sum(), pb.iloc[s].sum()
        d_lat.append(A.e_sum / A.e_size - B.e_sum / B.e_size)
        d_fcr.append(A.h_sum / max(A.h_size, 1) - B.h_sum / max(B.h_size, 1))
    A, B = pa.sum(), pb.sum()
    q = lambda v: [float(np.percentile(v, 2.5)), float(np.percentile(v, 97.5))]
    return {"n_turns": int(len(ids)), "lat_diff_s": float(A.e_sum / A.e_size - B.e_sum / B.e_size), "lat_ci_s": q(d_lat),
            "fcr_diff": float(A.h_sum / A.h_size - B.h_sum / B.h_size), "fcr_ci": q(d_fcr), "resamples": n}


def main() -> None:
    dev = ids_of("devtest")
    rows, preds = [], {}
    for d, nm in PUBLISHED.items():
        p = PUB / d
        if not p.exists():
            continue
        sp = json.loads((p / "manifest.json").read_text()).get("score_point")
        pred = pd.read_parquet(p / "predictions.parquet")
        rows.append({**_row(nm, pred[pred.id.astype(str).isin(dev)], sp), "kind": "published"})
    for d in MAIN:
        p = SRC / d
        if not (p / "predictions.parquet").exists():
            continue
        s = json.loads((p / "summary.json").read_text())
        pred = pd.read_parquet(p / "predictions.parquet")
        pred = pred[pred.id.astype(str).isin(dev)]
        preds[d] = (pred, s.get("score_point"))
        r = {**_row(name_of(d), pred, s.get("score_point")), "kind": "ours"}
        if s.get("frozen_knobs"):
            o = metrics.apply_knobs(pred, s["frozen_knobs"], s.get("score_point"))
            r["frozen"] = {"knobs": s["frozen_knobs"], "fcr": float(o.loc[o.label == "hold", "cut"].mean()), "mean_latency": float(o.loc[o.label == "eot", "latency"].mean())}
        rows.append(r)
    boot = None
    if {"pulse_eot_hi", "smart_turn_v32_fp32"} <= preds.keys():
        (a, sa), (b, sb) = preds["pulse_eot_hi"], preds["smart_turn_v32_fp32"]
        ka = {k: rows_by(rows, name_of("pulse_eot_hi"))["knobs_lat5"][k] for k in ("threshold", "action_delay", "timeout")}
        kb = {k: rows_by(rows, name_of("smart_turn_v32_fp32"))["knobs_lat5"][k] for k in ("threshold", "action_delay", "timeout")}
        boot = paired_bootstrap(a, b, ka, kb, sa, sb)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "rescored.json").write_text(json.dumps({"half": "devtest", "n_turns": len(dev), "rows": rows, "bootstrap_v01_minus_smartturn_fp32": boot}, indent=2, default=float))
    md = ["# eot-bench `hi` dev-test half (200 turns), rescored from saved predictions", "",
          "Generated by `python -m eval.rescore_devtest`. Same metric code and knob grid as eot-bench. The sealed 200-turn half is not scored here (eval/split.py).", "",
          "| System | FCR@300 | FCR@600 | Lat@5% | Lat@10% | n holds / EoTs |", "|---|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: (r["Lat@5%"] or 9)):
        md.append(f"| {r['system']} | {pct(r['FCR@300'])} | {pct(r['FCR@600'])} | {ms(r['Lat@5%'])} | {ms(r['Lat@10%'])} | {r['n_hold']} / {r['n_eot']} |")
    fr = [r for r in rows if r.get("frozen")]
    if fr:
        md += ["", "Deployable rows (knobs frozen on the dev clips, never chosen on eot-bench):", ""]
        for r in fr:
            k = r["frozen"]["knobs"]
            md.append(f"- {r['system']}: FCR {pct(r['frozen']['fcr'])} at mean latency {ms(r['frozen']['mean_latency'])} (th {k['threshold']:.2f}, delay {k['action_delay']:.1f} s, timeout {k['timeout']:.1f} s)")
    if boot:
        md += ["", f"Paired bootstrap over {boot['n_turns']} dev-test turns ({boot['resamples']} resamples), v0.1 minus Smart Turn v3.2 fp32, each at its own Lat@5% knobs: "
               f"latency {1000 * boot['lat_diff_s']:+.1f} ms (95% CI {1000 * boot['lat_ci_s'][0]:+.1f} to {1000 * boot['lat_ci_s'][1]:+.1f}), "
               f"FCR {100 * boot['fcr_diff']:+.2f} pp (95% CI {100 * boot['fcr_ci'][0]:+.2f} to {100 * boot['fcr_ci'][1]:+.2f})."]
    (OUT / "rescored.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


def rows_by(rows: list[dict], name: str) -> dict:
    return next(r for r in rows if r["system"] == name)


if __name__ == "__main__":
    main()
